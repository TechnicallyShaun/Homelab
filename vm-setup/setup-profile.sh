#!/bin/bash
# Setup bash profile with AI CLI aliases and custom MOTD
# Re-running this script will overwrite previous settings

set -e

PROFILE_MARKER="# >>> vm-setup-profile >>>"
PROFILE_END_MARKER="# <<< vm-setup-profile <<<"

echo "=========================================="
echo "Setting Up Bash Profile & MOTD"
echo "=========================================="

# Ask for MOTD title
echo ""
read -p "Enter a title for your MOTD (e.g., 'Dev VM', 'Techie Fun'): " MOTD_TITLE

if [ -z "$MOTD_TITLE" ]; then
    MOTD_TITLE="Dev VM"
fi

# Install figlet for ASCII art if not present
if ! command -v figlet &> /dev/null; then
    echo "Installing figlet for ASCII art..."
    sudo apt-get update -qq
    sudo apt-get install -y figlet
fi

# Clean up legacy entries from old versions of this script
echo ""
echo "Cleaning up old entries..."
sed -i '/# Load AI CLI aliases/d' ~/.bashrc 2>/dev/null || true
sed -i '/\.bash_ai_aliases/d' ~/.bashrc 2>/dev/null || true
sed -i '/# Display custom MOTD/d' ~/.bashrc 2>/dev/null || true
sed -i '/cat ~\/.motd/d' ~/.bashrc 2>/dev/null || true
rm -f ~/.motd ~/.bash_ai_aliases 2>/dev/null || true

# Remove existing profile block if present
sed -i "/$PROFILE_MARKER/,/$PROFILE_END_MARKER/d" ~/.bashrc 2>/dev/null || true

# Create the profile block
echo ""
echo "Creating bash profile..."

cat >> ~/.bashrc << 'EOF'

# >>> vm-setup-profile >>>
# AI CLI Quick Commands (YOLO modes) - managed by vm-setup/setup-profile.sh

alias ccyo='claude --dangerously-skip-permissions'
alias coyo='gh copilot --allow-all-tools'
alias ggyo='gemini --yolo'
alias cxyo='codex --yolo'
# <<< vm-setup-profile <<<
EOF

echo "Profile block added to ~/.bashrc"

# Disable default Ubuntu MOTD scripts
echo ""
echo "Configuring MOTD..."

# Disable all default MOTD scripts
sudo chmod -x /etc/update-motd.d/* 2>/dev/null || true

# Clear all static motd files
sudo rm -f /etc/motd /etc/motd.tail /run/motd.dynamic 2>/dev/null || true
sudo touch /etc/motd

# Create our custom MOTD script
sudo tee /etc/update-motd.d/00-custom > /dev/null << MOTDSCRIPT
#!/bin/bash
# Custom MOTD - generated by vm-setup/setup-profile.sh

# Title
figlet -f small "$MOTD_TITLE" 2>/dev/null || echo "$MOTD_TITLE"
echo ""

# System info
source /etc/os-release 2>/dev/null
KERNEL=\$(uname -r)
LOAD=\$(cat /proc/loadavg | awk '{print \$1, \$2, \$3}')
DISK_USAGE=\$(df -h / | awk 'NR==2 {print \$5 " of " \$2}')
MEM_USAGE=\$(free | awk '/Mem:/ {printf "%.1f%%", \$3/\$2 * 100}')
SWAP_USAGE=\$(free | awk '/Swap:/ {if(\$2>0) printf "%.1f%%", \$3/\$2 * 100; else print "N/A"}')

printf "%-14s %s (%s)\\n" "Version:" "\$PRETTY_NAME" "\$KERNEL"
printf "%-14s %s\\n" "System load:" "\$LOAD"
printf "%-14s %s\\n" "Usage of /:" "\$DISK_USAGE"
printf "%-14s %s\\n" "Memory usage:" "\$MEM_USAGE"
printf "%-14s %s\\n" "Swap usage:" "\$SWAP_USAGE"
echo ""

# Updates check
UPDATES=\$(apt-get -s upgrade 2>/dev/null | grep -c "^Inst" || echo "0")
if [ "\$UPDATES" -gt 0 ]; then
    echo "⚠ Updates available (\$UPDATES updates)"
    echo ""
fi

# Quick commands
echo "───────────────────────────────────────────────"
echo "Quick Commands:"
printf "  %-6s %-24s %-6s %s\\n" "ccyo" "- Claude Code" "coyo" "- Copilot"
printf "  %-6s %-24s %-6s %s\\n" "ggyo" "- Gemini" "cxyo" "- Codex"
echo "───────────────────────────────────────────────"
echo ""
MOTDSCRIPT

sudo chmod +x /etc/update-motd.d/00-custom

echo ""
echo "=========================================="
echo "Setup Complete!"
echo "=========================================="
echo ""
echo "Aliases created:"
echo "  ccyo - claude --dangerously-skip-permissions"
echo "  coyo - gh copilot --allow-all-tools"
echo "  ggyo - gemini --yolo"
echo "  cxyo - codex --yolo"
echo ""
echo "MOTD has been set with title: $MOTD_TITLE"
echo ""
echo "Run 'source ~/.bashrc' or start a new terminal to use the aliases."
echo ""
